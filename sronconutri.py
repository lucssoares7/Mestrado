def resultados_dietas(dietas_por_paciente, n_days, n_meals, n_foods_per_meal):

    resultados = []
    day_names = ["Segunda-feira", "Terça-feira", "Quarta-feira", "Quinta-feira", "Sexta-feira"]

    for paciente, dieta in dietas_por_paciente.items():
        res_obj = dieta.get('resultado_nsga2', None)
        df_alimentos = dieta.get('df_alimentos', None)
        # Verifica se os dados necessários estão disponíveis
        if res_obj is None or df_alimentos is None:
            print(f"Dados incompletos para o paciente {paciente}. Pulando...")
            continue

        # Extrai a melhor solução (assumindo que ela está em res_obj.X[0])
        if res_obj.X is None or len(res_obj.X) == 0:
            print(f"Sem solução para o paciente {paciente}. Pulando...")
            continue

        best_solution = list(map(int, res_obj.X[0]))
        total_expected = n_days * n_meals * n_foods_per_meal
        if len(best_solution) != total_expected:
            print(f"Solução de dimensão inesperada para o paciente {paciente}. Pulando...")
            continue

        # Percorre os dias e refeições
        for d in range(n_days):
            start_day = d * n_meals * n_foods_per_meal
            # Para cada refeição do dia:
            for m in range(n_meals):
                start_meal = start_day + m * n_foods_per_meal
                end_meal = start_meal + n_foods_per_meal
                meal_solution = best_solution[start_meal:end_meal]
                # Seleciona os alimentos correspondentes na base de dados
                meal_df = df_alimentos.iloc[meal_solution]
                # Itera sobre cada alimento selecionado na refeição
                for idx, row in meal_df.iterrows():
                    resultados.append({
                        'Paciente': paciente,
                        'Dia': day_names[d] if d < len(day_names) else f"Dia {d+1}",
                        'Refeição': f"Refeição {m+1}",
                        'Alimento': row["ALIMENTO"].split(',')[0].strip() if isinstance(row["ALIMENTO"], str) else "",
                        'Quantidade': 1,  # Se não houver informação de quantidade, usa 1
                        'Calorias': row.get("ENERGIA KCAL", 0),
                        'Proteína': row.get("PROTEÍNA", 0),
                        'Carboidrato': row.get("CARBOIDRATO TOTAL", 0),
                        'Lipídios': row.get("LIPÍDIOS", 0)
                    })

    df_resultados = pd.DataFrame(resultados)
    print("Linhas coletadas:", len(df_resultados))
    return df_resultados




def agrupar_por_alimento(df):
    """
    Agrupa os resultados por alimento, somando a quantidade, os macronutrientes e contando
    as ocorrências (quantas vezes o alimento foi utilizado).
    """
    df_agregado = df.groupby('Alimento').agg({
        'Quantidade': 'sum',
        'Calorias': 'sum',
        'Proteína': 'sum',
        'Carboidrato': 'sum',
        'Lipídios': 'sum',
        'Refeição': 'count'  # Conta quantas vezes o alimento aparece
    }).rename(columns={'Refeição': 'Ocorrências'}).reset_index()
    return df_agregado


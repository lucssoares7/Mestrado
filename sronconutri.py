import re

def split_raw_tables(latex_geral: str) -> list:
    """
    Separa uma string que contenha vários blocos '\begin{tabular}...\end{tabular}' concatenados
    em uma lista de strings, cada uma com exatamente um tabular completo.
    """
    pattern = r"(\\begin\{tabular\}.*?\\end\{tabular\})"
    blocos = re.findall(pattern, latex_geral, flags=re.DOTALL)
    return blocos


def resumir_nome_alimento(nome: str, max_words: int = 3) -> str:
    """
    Recebe o nome completo do alimento e retorna uma versão resumida contendo apenas as primeiras
    max_words palavras.

    - Remove espaços em excesso, converte para maiúsculas.
    - Elimina vírgulas e parênteses, dividindo depois em tokens de palavras.
    - Retorna as N primeiras palavras concatenadas. Se o nome tiver menos de N palavras, retorna inteiro.
    """
    if not isinstance(nome, str) or not nome.strip():
        return ""

    nome = nome.strip().upper()
    nome = nome.replace(",", "")
    nome = nome.replace("(", "").replace(")", "")
    palavras = nome.split()

    if len(palavras) <= max_words:
        return " ".join(palavras)
    else:
        return " ".join(palavras[:max_words])


def formatar_tabelas_latex_semanal(nome_paciente: str,
                                   latex_semanal_bruto: str,
                                   experimento_nome: str = "Experimento 3 (NSGA-II)",
                                   label_prefix: str = "tab:xp3nsga2",
                                   max_words_nome: int = 3) -> str:
    """
    Recebe:
      - nome_paciente: string com o nome (usada para gerar labels únicos);
      - latex_semanal_bruto: uma única string que contém N blocos \begin{tabular}...\end{tabular}
                              concatenados (um por dia);
      - experimento_nome: texto fixo que vai aparecer antes do dia no caption;
      - label_prefix: prefixo para os \label, seguido por '_{paciente}_{dia}';
      - max_words_nome: quantas palavras exibir no nome resumido do alimento.

    Retorna:
      - Uma única string contendo N ambientes “table” completos (um para cada dia encontrado),
        onde cada bloco é formatado com:
          • \begin{table}[H]
          • \caption{<experimento_nome>: <dia_da_semana>}
          • \label{<label_prefix>_<nome_paciente>_<índice>}
          • \footnotesize
          • \centering
          • \begin{tabular}{p{4cm} c r r r r}
          • (linhas resumidas de alimento + vírgula decimal)
          • \legend{\authorship}
          • \end{table}

    Observação:
      - O método assume que latex_semanal_bruto contém exatamente N blocos de tabular (por ex. N=5 para 5 dias).
      - Se encontrar mais do que 5 blocos, ignora o excedente. Se encontrar menos, gera apenas pelos dias disponíveis.
    """
    # Lista fixa de dias da semana (pode ajustar caso queira outro idioma ou mais dias)
    dias_semana = ["Segunda-feira", "Terça-feira", "Quarta-feira", "Quinta-feira", "Sexta-feira"]

    # 1) Separa os blocos de tabular
    raw_tables = split_raw_tables(latex_semanal_bruto)
    if not raw_tables:
        return ""  # Não encontrou nenhum \begin{tabular}

    latex_formatado = []
    qtd_dias = min(len(raw_tables), len(dias_semana))

    for i in range(qtd_dias):
        tabela_bruta = raw_tables[i]
        dia = dias_semana[i]
        # Gera um label único: pipoca_fernandes_3, por ex.
        label = f"{label_prefix}_{nome_paciente.replace(' ', '_').lower()}_{i+1}"

        # Cabeçalho do environment “table”
        cabecalho = [
            "\\begin{table}[H]",
            f"  \\caption{{{experimento_nome}: {dia}}}",
            f"  \\label{{{label}}}",
            "  \\footnotesize",
            "  \\centering"
        ]
        latex_formatado.extend(cabecalho)

        # 2) Troca colunas do tabular: {lrrrrr} → {p{4cm} c r r r r}
        tabular_formatado = tabela_bruta.replace(
            "\\begin{tabular}{lrrrrr}",
            "\\begin{tabular}{p{4cm} c r r r r}"
        )

        # 3) Agora percorrermos linha a linha, resumindo nome e ajustando vírgula decimal
        linhas = tabular_formatado.splitlines()
        novo_corpo = []
        dentro_do_tabular = False

        for linha in linhas:
            # Copiamos linhas de estrutura sem alterar
            if any(tag in linha for tag in ["\\toprule", "\\midrule", "\\bottomrule",
                                             "\\begin{tabular}", "\\end{tabular}", "\\multicolumn"]):
                novo_corpo.append(linha)
                if "\\midrule" in linha:
                    dentro_do_tabular = True
                continue

            # Se estivermos dentro do tabular e a linha tiver “&” e “\\”, é linha de dado
            if dentro_do_tabular and "&" in linha and "\\" in linha:
                partes = [p.strip() for p in linha.split("&")]
                nome_completo = partes[0]
                quantidade = partes[1]
                cal_str = partes[2]
                prot_str = partes[3]
                carb_str = partes[4]
                lip_str = partes[5].replace("\\\\", "").strip()

                # 4) Resumir nome para as primeiras max_words_palavras
                nome_reduzido = resumir_nome_alimento(nome_completo, max_words=max_words_nome)

                # 5) Converter ponto para vírgula nos valores numéricos
                cal_str = re.sub(r"(\d+)\.(\d{2})", r"\1,\2", cal_str)
                prot_str = re.sub(r"(\d+)\.(\d{2})", r"\1,\2", prot_str)
                carb_str = re.sub(r"(\d+)\.(\d{2})", r"\1,\2", carb_str)
                lip_str = re.sub(r"(\d+)\.(\d{2})", r"\1,\2", lip_str)

                # 6) Reconstrói a linha com nome resumido
                nova_linha = f"    {nome_reduzido} & {quantidade} & {cal_str} & {prot_str} & {carb_str} & {lip_str} \\\\"
                novo_corpo.append(nova_linha)
                continue

            # Caso contrário, copia a linha sem alterações
            novo_corpo.append(linha)

        # Une as linhas do tabular e adiciona ao resultado
        latex_formatado.extend(novo_corpo)

        # Fechamento do environment “table”
        latex_formatado.append("  \\legend{\\authorship}")
        latex_formatado.append("\\end{table}")
        latex_formatado.append("")  # linha em branco para separar dias

    return "\n".join(latex_formatado)


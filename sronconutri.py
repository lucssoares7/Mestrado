    def carregar_dados(self):
        """
        Lê o arquivo CSV usando apenas colunas em self.colunas_relevantes.
        Cada linha vira um dict, e retornamos uma lista ordenada por 'ALIMENTO'.
        """
        try:
            with open(self.nome_arquivo, newline='', mode='r', encoding='ISO-8859-1') as arquivo_csv:
                leitor = csv.DictReader(arquivo_csv, delimiter=',')
                dados_processados = []

                for linha in leitor:
                    linha_up = {}
                    for coluna, valor in linha.items():
                        # Se for ALIMENTO ou TIPO, convertemos para uppercase
                        col_up = coluna.upper()
                        if col_up in ['ALIMENTO', 'TIPO']:
                            linha_up[col_up] = valor.upper() if valor else valor
                        else:
                            linha_up[col_up] = valor
                    dados_processados.append(linha_up)

                # Ordena por 'ALIMENTO' (se existir na linha)
                dados_ordenados = sorted(
                    dados_processados,
                    key=lambda x: x.get('ALIMENTO', '').upper()
                )
                return dados_ordenados

        except FileNotFoundError:
            print(f"Erro: Arquivo {self.nome_arquivo} não encontrado.")
            return []

        except Exception as e:
            print(f"Ocorreu um erro ao carregar dados: {e}")
            return []


    def _normaliza_texto(self, s: str) -> str:
        """
        - Transforma em maiúsculas
        - Remove acentos (NFD + filtra marcas diacríticas)
        - Substitui hífen por espaço
        - Colapsa espaços múltiplos
        """
        if not isinstance(s, str):
            return ''
        s = s.strip().upper()

        # Remove acentos
        s = unicodedata.normalize('NFD', s)
        s = ''.join(ch for ch in s if unicodedata.category(ch) != 'Mn')

        # Substitui hífens por espaço e remove espaçamentos extras
        s = s.replace('-', ' ')
        s = re.sub(r'\s+', ' ', s)

        return s


    def _classifica_nome(self, nome: str) -> str:
        """
        - Recebe o nome bruto de um alimento (string)
        - Normaliza (remove acento, hífen, passa para maiúsculas)
        - Remove stopwords (DE, DO, DA, etc.)
        - Varre cada grupo e cada keyword;
          se encontrar \bKEYWORD\b dentro de nome normalizado, devolve o grupo.
        - Se nada bater, retorna 'OUTROS'.
        """
        if not isinstance(nome, str):
            return "OUTROS"

        # 1) Normalizar texto
        nome_norm = self._normaliza_texto(nome)

        # 2) Remover stopwords (artigos/preposições)
        tokens = [p for p in nome_norm.split() if p not in self.stopwords]
        nome_sem_stop = " ".join(tokens)

        # 3) Testar cada grupo
        for grupo_norm, lista_kws in self.grupos.items():
            for kw in lista_kws:
                pattern = r"\b" + re.escape(kw) + r"\b"
                if re.search(pattern, nome_sem_stop):
                    return grupo_norm

        return "OUTROS"


    def classificar_alimentos(self):
        """
        Popula/atualiza a chave 'TIPO' em cada linha de self.dados,
        chamando _classifica_nome para decidir o grupo.
        """
        for alimento in self.dados:
            nome_original = alimento.get('ALIMENTO', '')
            grupo = self._classifica_nome(nome_original)
            alimento['TIPO'] = grupo


    def definir_estado_fisico(self):
        """
        Preenche a chave 'ESTADO' em cada linha (SÓLIDO, LÍQUIDO ou DESCONHECIDO),
        baseado em substrings pré‐definidas.
        """
        estados = {
            "SÓLIDO": ["PÃO", "QUEIJO", "CARNE", "FRANGO", "BATATA", "ARROZ", "MASSA", "FRUTA", "LEGUME"],
            "LÍQUIDO": ["LEITE", "ÁGUA", "SUCO", "REFRIGERANTE", "BEBIDA", "CAFÉ", "CALDO", "SOPA", "IOGURTE", "VINHO"]
        }

        for alimento in self.dados:
            nome = alimento.get('ALIMENTO', '').upper().strip()
            estado_definido = False
            for estado, palavras_chave in estados.items():
                if any(p in nome for p in palavras_chave):
                    alimento['ESTADO'] = estado
                    estado_definido = True
                    break
            if not estado_definido:
                alimento['ESTADO'] = "DESCONHECIDO"



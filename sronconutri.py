def coletar_resultados_dietas_nsga_2(dietas_por_paciente: dict) -> pd.DataFrame:
    """
    Constrói um DataFrame com todas as refeições de todos os pacientes,
    a partir do dicionário `dietas_por_paciente` gerado no loop NSGA-II.

    Para cada paciente, espera-se que:
      dietas_por_paciente[nome]['dieta_semanal']['dias'][dia]['refeicoes']
      seja uma lista de objetos (ou dicts) onde cada objeto tenha
      informação sobre os alimentos consumidos.

    Cada 'item' em refeicao.alimentos pode ser um dict cujas chaves
    de nome do alimento podem variar entre 'alimento', 'Alimento' ou 'ALIMENTO'.
    Esta função tentará extrair o nome verificando todas essas possibilidades.
    """
    linhas = []

    for paciente_nome, info in dietas_por_paciente.items():
        dieta_semanal = info.get('dieta_semanal')
        if not dieta_semanal:
            # não há dieta para esse paciente
            continue

        dias_dict = dieta_semanal.get('dias', {})
        for dia, conteudo_dia in dias_dict.items():
            refeicoes = conteudo_dia.get('refeicoes', [])
            for refeicao in refeicoes:
                # 1) Descobre o nome da refeição (se houver)
                if hasattr(refeicao, 'nome'):
                    nome_refeicao = refeicao.nome
                else:
                    nome_refeicao = refeicao.get('nome', 'Refeição')

                # 2) Tenta extrair a lista de alimentos, que pode estar em refeicao.alimentos
                if hasattr(refeicao, 'alimentos'):
                    lista_alimentos = refeicao.alimentos
                else:
                    lista_alimentos = refeicao.get('alimentos', [])

                # 3) Para cada 'item' nessa lista, tenta achar o nome real do alimento
                for item in lista_alimentos:
                    # item pode ser dict ou outro. Se for string simples, converte diretamente:
                    if isinstance(item, str):
                        nome_item = item.strip()
                        quantidade = 1
                        calorias = proteina = carbo = lipidios = 0.0

                    else:
                        # Se chegou aqui, supomos dict; tenta extrair o nome via várias chaves:
                        nome_item = (
                            item.get('alimento') or
                            item.get('Alimento') or
                            item.get('ALIMENTO') or
                            ''
                        )
                        if isinstance(nome_item, str):
                            nome_item = nome_item.strip()
                        else:
                            nome_item = str(nome_item).strip()

                        # Se o usuário armazenou em item a quantidade e macros, as chaves
                        # podem ser 'quantidade', 'Quantidade', 'QUANTIDADE', etc.
                        quantidade = item.get('quantidade')
                        if quantidade is None:
                            quantidade = item.get('Quantidade', 1)
                        if quantidade is None:
                            quantidade = 1

                        calorias  = item.get('calorias')
                        if calorias is None:
                            calorias = item.get('Calorias', 0.0)
                        if calorias is None:
                            calorias = 0.0

                        proteina  = item.get('proteina')
                        if proteina is None:
                            proteina = item.get('Proteína', 0.0)
                        if proteina is None:
                            proteina = 0.0

                        carbo     = item.get('carboidrato')
                        if carbo is None:
                            carbo = item.get('Carboidrato', 0.0)
                        if carbo is None:
                            carbo = 0.0

                        lipidios  = item.get('lipidios')
                        if lipidios is None:
                            lipidios = item.get('Lipídios', 0.0)
                        if lipidios is None:
                            lipidios = 0.0

                    # 4) Se nome_item ficou vazio (''), pulamos este item
                    if not nome_item:
                        continue

                    # 5) Adiciona ao nosso array de linhas
                    linhas.append({
                        'Paciente': paciente_nome,
                        'Dia': dia,
                        'Refeição': nome_refeicao,
                        'Alimento': nome_item,
                        'Quantidade': quantidade,
                        'Calorias': calorias,
                        'Proteína': proteina,
                        'Carboidrato': carbo,
                        'Lipídios': lipidios
                    })

    df_resultados = pd.DataFrame(linhas)
    return df_resultados


    def buscarAlimentosRestritos(self, lista_alimentos_restritos):
        """
        Recebe lista de strings no formato:
          - "NOME_EXATO_DO_ALIMENTO"
          - OU: "GRUPO: item1,item2,item3"
        Retorna lista de dicionários cujo 'ALIMENTO' bate com as restrições.
        """
        if not isinstance(lista_alimentos_restritos, list):
            raise ValueError("A lista de alimentos restritos deve ser do tipo lista.")

        encontrados = []
        for alimento in self.dados:
            nome = alimento.get('ALIMENTO', '').strip()
            for restr in lista_alimentos_restritos:
                if ':' in restr:
                    # “GRUPO: item1,item2,...”
                    grupo_alim = restr.split(':', 1)[1]
                    itens = [i.strip() for i in grupo_alim.split(',')]
                    if nome in itens:
                        encontrados.append(alimento)
                        break
                else:
                    # Nome exato
                    if nome == restr.strip():
                        encontrados.append(alimento)
                        break
        return encontrados



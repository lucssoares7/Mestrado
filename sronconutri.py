    if 'TIPO' not in df.columns:
        raise KeyError("A coluna 'TIPO' não foi encontrada no DataFrame.")

    # Função interna de normalização: maiúsculas + remover acentos + colapsar espaços
    def _normaliza_texto(s: str) -> str:
        if not isinstance(s, str):
            return ''
        s = s.strip().upper()
        s = unicodedata.normalize('NFD', s)
        s = ''.join(ch for ch in s if unicodedata.category(ch) != 'Mn')
        s = s.replace('-', ' ')
        s = re.sub(r'\s+', ' ', s)
        return s

